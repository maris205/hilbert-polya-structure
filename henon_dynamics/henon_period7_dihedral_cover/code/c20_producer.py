def arithmetic_certificate() -> dict:
    alpha, z, T, sigma = sp.symbols("alpha z T sigma")
    cubic = alpha**3 + alpha**2 - 2 * alpha - 1
    if not sp.Poly(cubic, alpha, domain=sp.QQ).is_irreducible:
        raise AssertionError("cubic field polynomial reducible")
    if sp.discriminant(cubic, alpha) != 49:
        raise AssertionError("cubic field discriminant changed")
    b_exprs = {
        5: alpha**2 + 2 * alpha,
        11: 2 - alpha,
        13: alpha**2 - 1,
    }
    sigma0_witnesses = {5: 0, 11: 0, 13: 1}
    expected_c = {
        5: [1, 3, 11, 31, 55, 75, 125],
        11: [1, 7, 47, 161, 517, 847, 1331],
        13: [1, 2, 38, 51, 494, 338, 2197],
    }
    expected_minpoly = {
        5: z**3 - 3 * z**2 - 4 * z - 1,
        11: z**3 - 7 * z**2 + 14 * z - 7,
        13: z**3 - 2 * z**2 - z + 1,
    }
    expected_b = {
        5: ([1, 2, 4, 10, 25], 8, 30, [-2, -4]),
        11: ([1, 2, 1, 22, 121], 14, 120, [-2, 2]),
        13: ([1, -4, 12, -52, 169], 10, 178, [4, -8]),
    }
    rows = []
    q6 = q6_polynomial(sigma)
    q6_disc = int(sp.discriminant(q6, sigma))
    for p in PRIMES:
        if q6_disc % p == 0 or 64 % p == 0:
            raise AssertionError("selected prime is not good for B")
        n1, n2 = count_B(p)
        power_sums = [p + 1 - n1, p * p + 1 - n2]
        e1 = -power_sums[0]
        e2 = (power_sums[0] ** 2 - power_sums[1]) // 2
        lb = [1, e1, e2, p * e1, p * p]
        if (lb, n1, n2, power_sums) != expected_b[p]:
            raise AssertionError(f"B local factor changed at p={p}")

        b = b_exprs[p]
        b_minpoly = sp.factor(sp.resultant(cubic, z - b, alpha))
        if sp.expand(b_minpoly - expected_minpoly[p]) != 0:
            raise AssertionError(f"b_p minimal polynomial changed at p={p}")
        norm = sp.Poly(sp.expand(sp.resultant(cubic, 1 + b * T + p * T**2, alpha)), T)
        lc = [int(norm.nth(i)) for i in range(7)]
        if lc != expected_c[p]:
            raise AssertionError(f"C norm factor changed at p={p}")
        affine_counts = []
        node_splits = []

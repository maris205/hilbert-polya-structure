def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def orbit_polynomial() -> tuple[sp.Symbol, sp.Symbol, sp.Expr, sp.Expr]:
    x, sigma = sp.symbols("x sigma")
    a = sigma**2 - 2 * sigma
    p = (
        x**7
        - sigma * x**6
        - (3 * a - 2 * sigma) * x**5
        - (2 * a - (3 * a - 4) * sigma - 4) * x**4
        + (3 * a**2 - 2 * (2 * a - 1) * sigma + 1) * x**3
        + (4 * a**2 - 10 * a - (3 * a**2 - 8 * a + 1) * sigma - 2) * x**2
        - (a - 1) * (a**2 - 2 * a * sigma + a + 2) * x
        - 2 * a**3
        + 6 * a**2
        + 2 * a
        + 3
        + (a**3 - 4 * a**2 + a - 2) * sigma
    )
    return x, sigma, a, sp.expand(p)


def q6_polynomial(sigma: sp.Symbol) -> sp.Expr:
    return (
        64 * sigma**6
        - 448 * sigma**5
        + 848 * sigma**4
        + 80 * sigma**3
        - 1048 * sigma**2
        + 152 * sigma
        - 151
    )


def chronological_square_class() -> dict:
    """Compute the generic neighbor discriminant and its exact field norm."""
    x, sigma, a, p = orbit_polynomial()
    y = sp.symbols("y")
    field = sp.QQ.frac_field(sigma)
    pmod = sp.Poly(p, x, domain=field)
    py = sp.expand(p.subs(x, y))
    pnext = sp.expand(p.subs(x, a - y**2 - x))
    subresultants = sp.subresultants(py, pnext, y)

    rows: list[dict] = []
    last = None
    for sub in subresultants:
        poly_y = sp.Poly(sub, y)
        coeffs = [sp.Poly(c, x, domain=field).rem(pmod) for c in poly_y.all_coeffs()]
        zero = all(c.is_zero for c in coeffs)
        rows.append({"degree_in_y": int(poly_y.degree()), "zero_mod_P": bool(zero)})
        if not zero:
            last = coeffs
    expected_rows = [
        (14, False), (7, False), (6, False), (5, False), (4, False),
        (3, False), (2, False), (1, True), (0, True),
    ]
    if [(r["degree_in_y"], r["zero_mod_P"]) for r in rows] != expected_rows:
        raise AssertionError("neighbor subresultant pattern changed")
    if last is None or len(last) != 3:
        raise AssertionError("missing neighbor quadratic")
    c2, c1, c0 = last
    if not (c1 - c2 * sp.Poly(x**2 - a, x, domain=field)).rem(pmod).is_zero:
        raise AssertionError("neighbor-sum relation changed")

    raw_discriminant = (c1 * c1 - 4 * c2 * c0).rem(pmod)
    normalized = sp.cancel(raw_discriminant.as_expr() / c2.as_expr() ** 2)
    numerator, denominator = sp.fraction(normalized)
    norm_num = sp.factor(sp.resultant(p, numerator, x))
    norm_den = sp.factor(sp.resultant(p, denominator, x))
    norm = sp.factor(sp.cancel(norm_num / norm_den))
    q6 = q6_polynomial(sigma)
    if sp.expand(norm - q6) != 0:
        raise AssertionError("neighbor-discriminant norm is not Q6")

    # This specialization is a small nonsquare control independent of the
    # generic resultant simplification.
    if int(q6.subs(sigma, 3)) % 5 != 3:
        raise AssertionError("F_5 Q6 control changed")
    p5 = sp.Poly(p.subs(sigma, 3), x, modulus=5)
    if sp.factor_list(p5)[0] == 0 or int(sp.discriminant(p5.as_expr(), x)) % 5 != 3:
        raise AssertionError("F_5 regular-fibre control failed")

    return {
        "subresultant_reduction": rows,
        "generic_neighbor_degree": 2,
        "neighbor_sum_identity": "y_1+y_2=a-x^2",
        "normalized_neighbor_discriminant_sha256": sha256_text(str(normalized)),
        "norm_numerator_sha256": sha256_text(str(norm_num)),
        "norm_denominator_sha256": sha256_text(str(norm_den)),
        "norm_identity": "Norm_{Q(sigma,x)/Q(sigma)}(Delta)=Q6(sigma)",
        "norm_polynomial": str(q6),
        "norm_is_nonsquare": True,
        "nonsquare_control": {
            "prime": 5,
            "sigma": 3,
            "x_component": 0,
            "normalized_Delta": 2,
            "Q6": 3,
            "Delta_over_Q6": 4,
            "both_Delta_and_Q6_nonsquare": True,
        },
        "square_class_derivation": (
            "group-theoretic: the ordered-edge splitting field has G=D7; "
            "its unique sign quadratic is generated by sqrt(Disc_x(P)), "
            "hence by sqrt(Q6) because Disc_x(P)=(4*sigma-9)^2*Q6^3"
        ),
        "direct_square_root_identity_claimed": False,
    }


def branch_certificate() -> dict:
    x, sigma, _, p = orbit_polynomial()
    q6 = q6_polynomial(sigma)
    expected_disc = (4 * sigma - 9) ** 2 * q6**3
    if sp.expand(sp.factor(sp.discriminant(p, x)) - expected_disc) != 0:
        raise AssertionError("septic discriminant identity failed")
    qpoly = sp.Poly(q6, sigma, domain=sp.QQ)
    if not qpoly.is_irreducible:
        raise AssertionError("Q6 is reducible")
    qdisc = sp.factor(sp.discriminant(q6, sigma))
    if qdisc != 2**63 * 97:
        raise AssertionError("Q6 discriminant changed")

    u_numerator = -(
        160 * sigma**5
        - 760 * sigma**4
        + 412 * sigma**3
        + 1120 * sigma**2
        - 111 * sigma
        + 166
    )
    u = u_numerator / 4
    value = sp.cancel(p.subs(x, u))
    value_num = sp.fraction(value)[0]
    if not sp.Poly(value_num, sigma, domain=sp.QQ).rem(qpoly).is_zero:
        raise AssertionError("branch root formula does not satisfy P modulo Q6")
    derivative_value = sp.cancel(sp.diff(p, x).subs(x, u))
    derivative_num, derivative_den = sp.fraction(derivative_value)
    derivative_rem = sp.Poly(derivative_num, sigma, domain=sp.QQ).rem(qpoly).as_expr()
    derivative_rem = sp.cancel(derivative_rem / derivative_den)
    expected_rem = 2 * (8 * sigma**4 - 36 * sigma**3 + 16 * sigma**2 + 39 * sigma + 37)
    if sp.expand(derivative_rem - expected_rem) != 0:
        raise AssertionError("branch derivative remainder changed")
    derivative_resultant = sp.factor(sp.resultant(q6, expected_rem, sigma))
    if derivative_resultant != 2**42:
        raise AssertionError("branch derivative resultant changed")

    return {
        "septic_discriminant": str(expected_disc),
        "Q6": str(q6),
        "Q6_irreducible_over_Q": True,
        "Q6_discriminant": int(qdisc),
        "Q6_discriminant_factorization": "2^63*97",
        "finite_sign_branch_divisor": "Q6(sigma)=0 (six simple geometric points)",
        "branch_root_u": str(u),
        "P_at_u_mod_Q6": "0",
        "Px_at_u_mod_Q6": str(expected_rem),
        "resultant_Q6_Px_at_u_remainder": int(derivative_resultant),
        "resultant_factorization": "2^42",
        "branch_root_is_simple": True,
    }


def fp2_mul(a: tuple[int, int], b: tuple[int, int], p: int) -> tuple[int, int]:
    # t^2=2; 2 is a nonsquare for all three selected primes.
    return ((a[0] * b[0] + 2 * a[1] * b[1]) % p,
            (a[0] * b[1] + a[1] * b[0]) % p)


def fp2_pow(a: tuple[int, int], n: int, p: int) -> tuple[int, int]:
    out = (1, 0)
    while n:
        if n & 1:
            out = fp2_mul(out, a, p)
        a = fp2_mul(a, a, p)
        n >>= 1
    return out


def q6_pair(s: tuple[int, int], p: int) -> tuple[int, int]:
    coefficients = (-151, 152, -1048, 80, 848, -448, 64)
    out = (0, 0)
    for c in reversed(coefficients):
        out = fp2_mul(out, s, p)
        out = ((out[0] + c) % p, out[1])
    return out


def count_B(p: int) -> tuple[int, int]:
    sigma = sp.symbols("sigma")
    q6 = q6_polynomial(sigma)
    n1 = p + 2 + sum(
        0 if (v := int(q6.subs(sigma, s)) % p) == 0 else (1 if pow(v, (p - 1) // 2, p) == 1 else -1)
        for s in range(p)
    )
    character_sum = 0
    for a in range(p):
        for b in range(p):
            value = q6_pair((a, b), p)
            if value == (0, 0):
                chi = 0
            else:
                power = fp2_pow(value, (p * p - 1) // 2, p)
                if power not in ((1, 0), (p - 1, 0)):
                    raise AssertionError("F_p2 character computation failed")
                chi = 1 if power == (1, 0) else -1
            character_sum += chi
    n2 = p * p + 2 + character_sum
    return n1, n2


def convolve(left: list[int], right: list[int]) -> list[int]:
    out = [0] * (len(left) + len(right) - 1)
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            out[i + j] += a * b
    return out


def plane_coefficients(field, sigma):
    """Frozen P coefficients in descending x-degree over a finite field."""
    p = field.characteristic
    c = lambda n: field(n % p)
    a = sigma*sigma-c(2)*sigma
    return (
        c(1), -sigma, -(c(3)*a-c(2)*sigma),
        -(c(2)*a-(c(3)*a-c(4))*sigma-c(4)),
        c(3)*a**2-c(2)*(c(2)*a-c(1))*sigma+c(1),
        c(4)*a**2-c(10)*a-(c(3)*a**2-c(8)*a+c(1))*sigma-c(2),
        -(a-c(1))*(a**2-c(2)*a*sigma+a+c(2)),
        -c(2)*a**3+c(6)*a**2+c(2)*a+c(3)+(a**3-c(4)*a**2+a-c(2))*sigma,
    )


def plane_affine_count(p: int, r: int) -> tuple[int, bool]:
    """Count P(sigma,x)=0 over F_{p^r} and test node splitting."""
    field = galois.GF(p**r)
    xs = field.elements
    total = 0
    for sigma in xs:
        coefficients = plane_coefficients(field, sigma)
        values = field.Zeros(xs.shape) + coefficients[0]
        for coefficient in coefficients[1:]:
            values = values*xs + coefficient
        total += int(np.count_nonzero(values == 0))
    node_splits = bool(field((-7) % p)**((field.order-1)//2) == 1)
    return total, node_splits


def reconstruct_genus3_factor(p: int, counts: list[int]) -> tuple[list[int], list[int]]:
    power_sums = [p**r+1-counts[r-1] for r in (1,2,3)]
    s1, s2, s3 = power_sums
    e1 = s1
    e2 = (e1*s1-s2)//2
    e3 = (s3-e1*s2+e2*s1)//3
    return power_sums, [1, -e1, e2, -e3, p*e2, p**2*(-e1), p**3]


def weighted_initial_form(
    expression: sp.Expr,
    variables: tuple[sp.Symbol, sp.Symbol],
    weights: tuple[int, int],
) -> sp.Expr:
    terms = sp.Poly(sp.expand(expression), *variables).terms()
    minimum = min(sum(e*w for e, w in zip(exponents, weights)) for exponents, _ in terms)
    return sp.factor(sum(
        coefficient * sp.prod(variable**exponent for variable, exponent in zip(variables, exponents))
        for exponents, coefficient in terms
        if sum(e*w for e, w in zip(exponents, weights)) == minimum
    ))



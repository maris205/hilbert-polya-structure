def expected_square_rows() -> list[dict]:
    rows = []
    for square_root in range(2, 16):
        delta = square_root * square_root
        candidates = []
        for form_a in range(1, square_root + 1):
            for form_b in range(-square_root + 1, square_root):
                numerator = form_b * form_b - delta
                if numerator % (4 * form_a):
                    continue
                form_c = numerator // (4 * form_a)
                if math.gcd(math.gcd(form_a, abs(form_b)), abs(form_c)) != 1:
                    continue
                p, q = -form_b, 2 * form_a
                value, conjugate = Fraction(p + square_root, q), Fraction(p - square_root, q)
                if value > 1 and -1 < conjugate < 0:
                    candidates.append((p, q, value))
        if not candidates:
            rows.append({"delta": delta, "strict_rational_states": 0, "seed": None, "digits_before_integer": [], "terminal_integer": None})
            continue
        p, q, value = min(candidates)
        digits = []
        while value.denominator != 1:
            floor_value = value.numerator // value.denominator
            digits.append(floor_value); value = 1 / (value - floor_value)
        rows.append({"delta": delta, "strict_rational_states": len(candidates), "seed": [p, q], "digits_before_integer": digits, "terminal_integer": value.numerator})
    return rows



def typed_equal(actual, expected) -> bool:
    """Recursive equality that never conflates JSON booleans, integers, or floats."""
    if type(actual) is not type(expected):
        return False
    if type(expected) is dict:
        return set(actual) == set(expected) and all(
            typed_equal(actual[key], expected[key]) for key in expected
        )
    if type(expected) is list:
        return len(actual) == len(expected) and all(
            typed_equal(left, right) for left, right in zip(actual, expected)
        )
    return actual == expected


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def unique(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise ValueError("duplicate JSON key")
        out[key] = value
    return out


class UniqueLoader(yaml.SafeLoader):
    pass


def unique_mapping(loader, node, deep=False):
    out = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if type(key) is not str or key in out:
            raise ValueError("non-string or duplicate YAML key")
        out[key] = loader.construct_object(value_node, deep=deep)
    return out


UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def parse_yaml(raw: bytes):
    for token in yaml.scan(raw):
        if isinstance(token, (AliasToken, AnchorToken)):
            raise ValueError("YAML alias or anchor")
    value = yaml.load(raw, Loader=UniqueLoader)
    if type(value) is not dict:
        raise ValueError("YAML root")
    return value


def leaves(value) -> int:
    if type(value) is dict:
        return sum(leaves(v) for v in value.values())
    if type(value) is list:
        return sum(leaves(v) for v in value)
    return 1


def root_gt_integer(delta: int, p: int, q: int, n: int) -> bool:
    bound = n * q - p
    return bound < 0 or bound * bound < delta


def independent_states(delta: int) -> list[tuple[int, int]]:
    """Enumerate primitive forms [A,B,C], then translate to (P,Q)."""
    s = math.isqrt(delta)
    found = []
    for form_a in range(1, s + 1):
        for form_b in range(-s, s + 1):
            numerator = form_b * form_b - delta
            if numerator % (4 * form_a):
                continue
            form_c = numerator // (4 * form_a)
            if math.gcd(math.gcd(form_a, abs(form_b)), abs(form_c)) != 1:
                continue
            p, q = -form_b, 2 * form_a
            if p >= 0 and p * p >= delta:
                continue
            if p + q <= 0 or (p + q) * (p + q) <= delta:
                continue
            if not root_gt_integer(delta, p, q, 1):
                continue
            found.append((p, q))
    return sorted(found)


def independent_digit(delta: int, state: tuple[int, int]) -> int:
    p, q = state
    estimate = (p + math.isqrt(delta)) // q
    while root_gt_integer(delta, p, q, estimate + 1):
        estimate += 1
    while estimate > 0 and not root_gt_integer(delta, p, q, estimate):
        estimate -= 1
    return estimate


def independent_step(delta: int, state: tuple[int, int]) -> tuple[int, int]:
    p, q = state
    a = independent_digit(delta, state)
    next_p = a * q - p
    return next_p, (delta - next_p * next_p) // q


def independent_reverse(delta: int, state: tuple[int, int]) -> tuple[int, int]:
    p, q = state
    return p, (delta - p * p) // q


def independent_cycles(delta: int, states: list[tuple[int, int]]) -> list[list[tuple[int, int]]]:
    permutation = {state: independent_step(delta, state) for state in states}
    unused, cycles = set(states), []
    while unused:
        start = min(unused)
        row, current = [], start
        while True:
            row.append(current); unused.remove(current); current = permutation[current]
            if current == start:
                break
        cycles.append(row)
    return cycles


def independent_matrix(digits: list[int]) -> list[list[int]]:
    aa, bb, cc, dd = 1, 0, 0, 1
    for digit_value in digits:
        aa, bb, cc, dd = aa * digit_value + bb, aa, cc * digit_value + dd, cc
    return [[aa, bb], [cc, dd]]



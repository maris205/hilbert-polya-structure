    keys(data["scope_flags"], flags, "scope_flags")
    check(data["schema"] == "hcs-c223-jaynes-cummings-v1" and data["candidate_id"] == "HCS-C223", "identity")
    check(data["evaluation_date"] == "2026-08-28" and data["source_commit"] == SOURCE_COMMIT, "date/source")
    check(data["scope_literal"] == SCOPE and data["evaluator"] == EVALUATOR and data["headline"] == HEADLINE, "locks")

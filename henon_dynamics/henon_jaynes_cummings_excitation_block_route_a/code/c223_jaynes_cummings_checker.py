    check(data["route_a"]["tuple"] == ["A0_FAIL", "A1_FAIL", "A2_FAIL", "A3_FAIL", "A4_NATURAL_QUANTIZATION"], "route tuple")
    check(data["route_a"]["overall"] == "ROUTE_A_REJECTED" and data["route_a"]["route_b_invocation_allowed"] is False, "route verdict")
    check(all(value is False for value in data["scope_flags"].values()), "scope flags")
    check(data["payload_sha256"] == payload_hash(data), "payload hash")

    expected_params = [{"parameter_label": label, "omega_c": str(wc), "omega_q": str(wq), "g": str(g)} for label, wc, wq, g in PARAMETERS]
    check(data["regression"]["parameter_rows"] == expected_params, "parameter rows")
    check(data["regression"]["n_values"] == N_VALUES and data["regression"]["t_values"] == [str(t) for t in T_VALUES], "grids")
    lookup = {label: (wc, wq, g) for label, wc, wq, g in PARAMETERS}
    tol = mp.mpf("1e-70")
    block_keys = ["case_id", "parameter_label", "omega_c", "omega_q", "g", "n", "center_energy", "detuning", "rabi_frequency_squared", "rabi_frequency", "lower_energy", "upper_energy", "block_trace", "block_determinant", "mixing_fraction"]
    seen = set()
    for i, row in enumerate(data["regression"]["block_rows"]):
        keys(row, block_keys, f"block[{i}]")
        check(row["parameter_label"] in lookup and row["n"] in N_VALUES, f"block[{i}] domain")

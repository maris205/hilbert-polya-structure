        check(ident not in seen, f"block[{i}] duplicate")
        seen.add(ident)
        check(row["case_id"] == f"{label}_n{n}" and (row["omega_c"], row["omega_q"], row["g"]) == (str(wc), str(wq), str(g)), f"block[{i}] identity")

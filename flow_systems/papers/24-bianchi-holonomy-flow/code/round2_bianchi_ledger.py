Gaussian = tuple[int, int]
Matrix = tuple[Gaussian, Gaussian, Gaussian, Gaussian]
Word = tuple[str, ...]

ZERO: Gaussian = (0, 0)
ONE: Gaussian = (1, 0)
I_GAUSSIAN: Gaussian = (0, 1)
IDENTITY: Matrix = (ONE, ZERO, ZERO, ONE)

MAX_WORD_LENGTH = 5
SHUFFLE_SEED_LABEL = "P24-2026-08-27-target-free-holonomy-shuffle-v1"
COMPLETENESS_BOUNDARY = (
    "ELEMENTARY_GENERATED_SUBGROUP_REDUCED_WORD_BALL_LE_5;"
    "NOT_FULL_GAMMA3;NOT_FULL_CONJUGACY_ENUMERATION"
)


def g_add(x: Gaussian, y: Gaussian) -> Gaussian:
    return (x[0] + y[0], x[1] + y[1])


def g_neg(x: Gaussian) -> Gaussian:
    return (-x[0], -x[1])


def g_mul(x: Gaussian, y: Gaussian) -> Gaussian:
    return (x[0] * y[0] - x[1] * y[1], x[0] * y[1] + x[1] * y[0])


def g_square(x: Gaussian) -> Gaussian:
    return g_mul(x, x)


def g_mod3(x: Gaussian) -> Gaussian:
    return (x[0] % 3, x[1] % 3)


def g_to_text(x: Gaussian) -> str:
    a, b = x
    if b == 0:
        return str(a)
    if a == 0:
        return "i" if b == 1 else "-i" if b == -1 else f"{b}i"
    sign = "+" if b > 0 else "-"
    coeff = "" if abs(b) == 1 else str(abs(b))
    return f"{a}{sign}{coeff}i"


def mat_mul(a: Matrix, b: Matrix) -> Matrix:
    a00, a01, a10, a11 = a
    b00, b01, b10, b11 = b
    return (
        g_add(g_mul(a00, b00), g_mul(a01, b10)),
        g_add(g_mul(a00, b01), g_mul(a01, b11)),
        g_add(g_mul(a10, b00), g_mul(a11, b10)),
        g_add(g_mul(a10, b01), g_mul(a11, b11)),
    )


def mat_det(a: Matrix) -> Gaussian:
    return g_add(g_mul(a[0], a[3]), g_neg(g_mul(a[1], a[2])))


def mat_trace(a: Matrix) -> Gaussian:
    return g_add(a[0], a[3])


def mat_inv(a: Matrix) -> Matrix:
    if mat_det(a) != ONE:
        raise ValueError("matrix is not in SL_2")
    return (a[3], g_neg(a[1]), g_neg(a[2]), a[0])


def mat_pow(a: Matrix, exponent: int) -> Matrix:
    if exponent < 0:
        return mat_pow(mat_inv(a), -exponent)
    result = IDENTITY
    base = a
    n = exponent
    while n:
        if n & 1:
            result = mat_mul(result, base)
        base = mat_mul(base, base)
        n >>= 1
    return result


def mat_flat(a: Matrix) -> tuple[int, ...]:
    return tuple(coordinate for entry in a for coordinate in entry)


def mat_text(a: Matrix) -> str:
    return f"[[{g_to_text(a[0])},{g_to_text(a[1])}],[{g_to_text(a[2])},{g_to_text(a[3])}]]"


def matrix_id(a: Matrix) -> str:
    raw = ",".join(str(x) for x in mat_flat(a)).encode("ascii")
    return "M" + hashlib.sha256(raw).hexdigest()[:16]


def in_level_three(a: Matrix) -> bool:
    residues = tuple(g_mod3(x) for x in a)
    return residues == (ONE, ZERO, ZERO, ONE)


def elementary_generators() -> tuple[dict[str, Matrix], dict[str, str], tuple[str, ...]]:
    three = (3, 0)
    three_i = g_mul(three, I_GAUSSIAN)
    positive = {
        "U1": (ONE, three, ZERO, ONE),
        "Ui": (ONE, three_i, ZERO, ONE),
        "L1": (ONE, ZERO, three, ONE),
        "Li": (ONE, ZERO, three_i, ONE),
    }
    generators: dict[str, Matrix] = {}
    inverse_name: dict[str, str] = {}
    order: list[str] = []
    for name in ("U1", "Ui", "L1", "Li"):
        inverse = name + "m"
        generators[name] = positive[name]
        generators[inverse] = mat_inv(positive[name])
        inverse_name[name] = inverse
        inverse_name[inverse] = name
        order.extend((name, inverse))
    return generators, inverse_name, tuple(order)


GENERATORS, INVERSE_NAME, GENERATOR_ORDER = elementary_generators()


def word_text(word: Word) -> str:
    return ".".join(word) if word else "e"


def inverse_word(word: Word) -> Word:
    return tuple(INVERSE_NAME[name] for name in reversed(word))


def canonical_rotation(word: Word) -> Word:
    if not word:
        return word
    return min(word[index:] + word[:index] for index in range(len(word)))


def symbolic_root(word: Word) -> tuple[Word, int]:
    n = len(word)
    if n == 0:
        return word, 1
    for size in range(1, n):
        if n % size == 0:
            root = word[:size]
            exponent = n // size
            if root * exponent == word:
                return root, exponent
    return word, 1


def enumerate_word_ball(max_word_length: int = MAX_WORD_LENGTH) -> dict[Matrix, dict[str, object]]:
    records: dict[Matrix, dict[str, object]] = {
        IDENTITY: {"representative": (), "word_collision_count": 1}
    }
    frontier: list[tuple[Word, Matrix]] = [((), IDENTITY)]
    for _length in range(1, max_word_length + 1):
        next_frontier: list[tuple[Word, Matrix]] = []
        for word, matrix in frontier:
            for name in GENERATOR_ORDER:
                if word and INVERSE_NAME[name] == word[-1]:
                    continue
                new_word = word + (name,)
                new_matrix = mat_mul(matrix, GENERATORS[name])
                next_frontier.append((new_word, new_matrix))
                record = records.get(new_matrix)
                if record is None:
                    records[new_matrix] = {
                        "representative": new_word,
                        "word_collision_count": 1,
                    }
                else:
                    record["word_collision_count"] = int(record["word_collision_count"]) + 1
                    if new_word < record["representative"]:
                        record["representative"] = new_word
        frontier = next_frontier
    return records


def classification(matrix: Matrix) -> str:
    if matrix == IDENTITY:
        return "IDENTITY"
    trace = mat_trace(matrix)
    if g_square(trace) == (4, 0):
        return "PARABOLIC"
    return "LOXODROMIC"


def complex_length(trace: Gaussian) -> tuple[float, float, float]:
    trace_complex = complex(trace[0], trace[1])
    value = 2.0 * cmath.acosh(trace_complex / 2.0)
    if value.real < 0:
        value = -value
    theta = ((value.imag + math.pi) % (2.0 * math.pi)) - math.pi
    if theta <= -math.pi + 1e-14:
        theta = math.pi
    normalized = complex(value.real, theta)
    reconstructed = 2.0 * cmath.cosh(normalized / 2.0)
    # The ledger is for the projected PSL_2(C) element.  Normalizing the
    # holonomy angle modulo 2*pi may exchange the two SL_2 lifts, so the trace
    # identity is projectively valid up to sign.
    residual = min(abs(reconstructed - trace_complex), abs(reconstructed + trace_complex))
    return normalized.real, normalized.imag, residual


def exact_power_roots(
    elements: dict[Matrix, dict[str, object]], max_exponent: int = MAX_WORD_LENGTH
) -> dict[Matrix, tuple[Matrix, int]]:
    roots: dict[Matrix, tuple[Matrix, int]] = {}
    ordered = sorted(
        (matrix for matrix in elements if matrix != IDENTITY),
        key=lambda matrix: (len(elements[matrix]["representative"]), mat_flat(matrix)),
    )
    for root in ordered:
        candidate = root
        for exponent in range(2, max_exponent + 1):
            candidate = mat_mul(candidate, root)
            if candidate not in elements:
                continue
            current = roots.get(candidate)
            proposal_key = (
                len(elements[root]["representative"]),
                exponent,
                mat_flat(root),
            )
            if current is None:
                roots[candidate] = (root, exponent)
            else:
                current_key = (
                    len(elements[current[0]]["representative"]),
                    current[1],
                    mat_flat(current[0]),
                )
                if proposal_key < current_key:
                    roots[candidate] = (root, exponent)
    return roots


def _float(value: float) -> str:
    return format(value, ".15g")


def _corr(xs: list[float], ys: list[float]) -> float:
    if len(xs) < 2:
        return 0.0
    mean_x = sum(xs) / len(xs)
    mean_y = sum(ys) / len(ys)
    dx = [x - mean_x for x in xs]
    dy = [y - mean_y for y in ys]
    denominator = math.sqrt(sum(x * x for x in dx) * sum(y * y for y in dy))
    if denominator == 0:
        return 0.0
    return sum(x * y for x, y in zip(dx, dy, strict=True)) / denominator


def phase_length_score(lengths: list[float], angles: list[float]) -> float:
    return math.hypot(
        _corr(lengths, [math.cos(angle) for angle in angles]),
        _corr(lengths, [math.sin(angle) for angle in angles]),
    )



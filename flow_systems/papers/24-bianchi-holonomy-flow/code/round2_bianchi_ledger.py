#!/usr/bin/env python3
"""Deterministic Round-2 word-ball ledger for a level-(3) Bianchi subgroup.

This program deliberately enumerates only the word ball in the subgroup
generated by four elementary level-(3) matrices.  It does not claim that this
generator set is all of Gamma((3)), that the word ball is a conjugacy-class
fundamental domain, or that a row owns a Gaussian/rational prime.
"""


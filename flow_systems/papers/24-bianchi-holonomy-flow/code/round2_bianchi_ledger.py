def build_payload(max_word_length: int = MAX_WORD_LENGTH) -> tuple[list[dict[str, str]], list[dict[str, str]], dict[str, object]]:
    elements = enumerate_word_ball(max_word_length)
    power_roots = exact_power_roots(elements, max_word_length)
    trace_counts = Counter(mat_trace(matrix) for matrix in elements)
    rows: list[dict[str, str]] = []

    for matrix in sorted(elements, key=mat_flat):
        record = elements[matrix]
        word = record["representative"]
        assert isinstance(word, tuple)
        matrix_class = classification(matrix)
        trace = mat_trace(matrix)
        if matrix_class == "LOXODROMIC":
            length, theta, residual = complex_length(trace)
        else:
            length, theta, residual = math.nan, math.nan, 0.0

        symbolic_base, symbolic_exponent = symbolic_root(word)
        exact_root = power_roots.get(matrix)
        if exact_root is None:
            exact_root_id = ""
            exact_exponent = 1
        else:
            exact_root_id = matrix_id(exact_root[0])
            exact_exponent = exact_root[1]

        if matrix_class == "LOXODROMIC" and exact_exponent == 1:
            primitive_status = "PRIMITIVE_WITHIN_WORD_BALL_NOT_GROUP_CERTIFIED"
        elif matrix_class == "LOXODROMIC":
            primitive_status = "REPETITION_CERTIFIED_WITHIN_ENUMERATED_SET"
        else:
            primitive_status = "NOT_A_LOXODROMIC_PERIODIC_OBJECT"

        inverse = mat_inv(matrix)
        paired = sorted((mat_flat(matrix), mat_flat(inverse)))
        pair_raw = repr(paired).encode("ascii")
        orientation_pair_id = "O" + hashlib.sha256(pair_raw).hexdigest()[:16]
        orientation = "CANONICAL" if mat_flat(matrix) <= mat_flat(inverse) else "REVERSED"

        cyclic = canonical_rotation(word)
        unoriented = min(cyclic, canonical_rotation(inverse_word(word)))
        if matrix_class == "IDENTITY":
            cusp_risk = "IDENTITY_NOT_ORBIT"
        elif matrix_class == "PARABOLIC":
            cusp_risk = "PARABOLIC_CUSP_ELEMENT_EXCLUDED_FROM_CLOSED_GEODESICS"
        else:
            cusp_risk = "GLOBAL_CUSP_SCATTERING_TERMS_NOT_COMPUTED"

        rows.append(
            {
                "row_id": matrix_id(matrix),
                "representative_word": word_text(word),
                "word_length": str(len(word)),
                "matrix": mat_text(matrix),
                "determinant": g_to_text(mat_det(matrix)),
                "level3_membership": "true" if in_level_three(matrix) else "false",
                "matrix_class": matrix_class,
                "trace_re": str(trace[0]),
                "trace_im": str(trace[1]),
                "complex_length_re": "" if math.isnan(length) else _float(length),
                "holonomy_angle": "" if math.isnan(theta) else _float(theta),
                "trace_reconstruction_residual": _float(residual),
                "symbolic_cyclic_class": word_text(cyclic),
                "symbolic_unoriented_class": word_text(unoriented),
                "symbolic_root": word_text(symbolic_base),
                "symbolic_repetition_exponent": str(symbolic_exponent),
                "exact_power_root_id": exact_root_id,
                "exact_power_exponent": str(exact_exponent),
                "primitive_status": primitive_status,
                "orientation_pair_id": orientation_pair_id,
                "orientation": orientation,
                "word_collision_multiplicity": str(record["word_collision_count"]),
                "trace_collision_multiplicity": str(trace_counts[trace]),
                "parabolic_cusp_risk": cusp_risk,
                "conjugacy_scope": "SYMBOLIC_CYCLIC_CLASS_ONLY_NOT_FULL_GROUP_CONJUGACY",
                "completeness_boundary": COMPLETENESS_BOUNDARY,
                "evidence_status": "NUMERICALLY_CERTIFIED",
            }
        )

    control_candidates = [
        row
        for row in rows
        if row["matrix_class"] == "LOXODROMIC" and row["exact_power_exponent"] == "1"
    ]
    source_order = sorted(
        control_candidates,
        key=lambda row: hashlib.sha256(
            f"{SHUFFLE_SEED_LABEL}:{row['row_id']}".encode("utf-8")
        ).hexdigest(),
    )
    controls: list[dict[str, str]] = []
    for target, source in zip(control_candidates, source_order, strict=True):
        theta = float(target["holonomy_angle"])
        source_theta = float(source["holonomy_angle"])
        controls.append(
            {
                "control_id": "HC" + target["row_id"][1:],
                "row_id": target["row_id"],
                "complex_length_fixed": target["complex_length_re"],
                "repetition_exponent_fixed": target["exact_power_exponent"],
                "original_holonomy_angle": target["holonomy_angle"],
                "shuffled_holonomy_angle": source["holonomy_angle"],
                "shuffled_from_row_id": source["row_id"],
                "orientation_reversal_angle": _float(-theta),
                "shuffle_seed_label": SHUFFLE_SEED_LABEL,
                "target_data_used": "false",
                "evidence_status": "NUMERICALLY_CERTIFIED",
            }
        )

    class_counts = Counter(row["matrix_class"] for row in rows)
    primitive_count = sum(
        row["primitive_status"] == "PRIMITIVE_WITHIN_WORD_BALL_NOT_GROUP_CERTIFIED"
        for row in rows
    )
    repetition_count = sum(
        row["primitive_status"] == "REPETITION_CERTIFIED_WITHIN_ENUMERATED_SET"
        for row in rows
    )
    lengths = [float(row["complex_length_fixed"]) for row in controls]
    original_angles = [float(row["original_holonomy_angle"]) for row in controls]
    shuffled_angles = [float(row["shuffled_holonomy_angle"]) for row in controls]
    metrics: dict[str, object] = {
        "candidate_id": "P24-BIANCHI-LEVEL3-ELEMENTARY-WORDBALL-R2",
        "generated_on": "2026-08-27",
        "max_reduced_word_length": max_word_length,
        "generator_names": list(GENERATOR_ORDER),
        "generator_claim": "FOUR_ELEMENTARY_GENERATORS_AND_INVERSES_ONLY",
        "enumerated_reduced_words_including_identity": 1
        + sum(8 * (7 ** (length - 1)) for length in range(1, max_word_length + 1)),
        "unique_exact_matrices": len(rows),
        "identity_rows": class_counts["IDENTITY"],
        "parabolic_rows": class_counts["PARABOLIC"],
        "loxodromic_rows": class_counts["LOXODROMIC"],
        "primitive_within_word_ball_not_group_certified": primitive_count,
        "certified_repetitions_within_enumerated_set": repetition_count,
        "holonomy_shuffle_rows": len(controls),
        "phase_length_score_original": phase_length_score(lengths, original_angles),
        "phase_length_score_shuffled": phase_length_score(lengths, shuffled_angles),
        "holonomy_control_evidence": "NUMERICAL_OBSERVATION",
        "holonomy_control_verdict": "OPEN",
        "max_trace_reconstruction_residual": max(
            float(row["trace_reconstruction_residual"]) for row in rows
        ),
        "all_determinants_one": all(row["determinant"] == "1" for row in rows),
        "all_level3_membership": all(row["level3_membership"] == "true" for row in rows),
        "all_orientation_inverses_present": all(mat_inv(matrix) in elements for matrix in elements),
        "prime_or_zero_tables_used": False,
        "orbit_to_prime_ideal_map": "OPEN_NOT_ESTABLISHED",
        "full_gamma3_enumeration": "OPEN_NOT_ESTABLISHED",
        "full_conjugacy_enumeration": "OPEN_NOT_ESTABLISHED",
        "formal_route_a_tuple": "UNASSIGNED",
        "route_b_evaluation": "NOT_RUN",
        "route_b_invocation_allowed": False,
        "completeness_boundary": COMPLETENESS_BOUNDARY,
        "evidence_status": "NUMERICALLY_CERTIFIED",
    }
    return rows, controls, metrics


def csv_bytes(rows: Iterable[dict[str, str]], fieldnames: list[str]) -> bytes:
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=fieldnames, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return stream.getvalue().encode("utf-8")


def json_bytes(payload: object) -> bytes:
    return (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode("utf-8")


def core_outputs(max_word_length: int = MAX_WORD_LENGTH) -> tuple[dict[str, bytes], dict[str, object]]:
    rows, controls, metrics = build_payload(max_word_length)
    outputs = {
        "results/bianchi_complex_length_ledger_round2.csv": csv_bytes(rows, LEDGER_FIELDS),
        "results/bianchi_holonomy_shuffle_control_round2.csv": csv_bytes(controls, CONTROL_FIELDS),
        "results/round2_metrics.json": json_bytes(metrics),
    }
    return outputs, metrics


def combined_hash(outputs: dict[str, bytes]) -> str:
    digest = hashlib.sha256()
    for name in sorted(outputs):
        digest.update(name.encode("utf-8"))
        digest.update(b"\0")
        digest.update(outputs[name])
        digest.update(b"\0")
    return digest.hexdigest()


